#!/usr/bin/env bash
# Idempotent Cloud Agent install script for next-multitenant-2024.
# Prepares a local PostgreSQL database plus Node dependencies, generated Prisma
# client, applied migrations, and seed data. Safe to run repeatedly.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_DIR"

PG_VERSION=16
PG_CLUSTER=main
DB_NAME=multitenant
DB_USER=postgres
DB_PASS=postgres

echo "==> Ensuring PostgreSQL ${PG_VERSION} is installed"
if ! command -v psql >/dev/null 2>&1; then
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    postgresql postgresql-contrib
fi

echo "==> Ensuring the PostgreSQL cluster is running"
if ! sudo pg_lsclusters -h | awk '{print $1"/"$2}' | grep -qx "${PG_VERSION}/${PG_CLUSTER}"; then
  sudo pg_createcluster "${PG_VERSION}" "${PG_CLUSTER}"
fi
sudo pg_ctlcluster "${PG_VERSION}" "${PG_CLUSTER}" start >/dev/null 2>&1 || true

echo "==> Waiting for PostgreSQL to accept connections"
for _ in $(seq 1 30); do
  if sudo -u postgres pg_isready -q; then break; fi
  sleep 1
done

echo "==> Ensuring database role and database exist"
sudo -u postgres psql -v ON_ERROR_STOP=1 -qtc \
  "ALTER USER ${DB_USER} WITH PASSWORD '${DB_PASS}';"
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='${DB_NAME}'" | grep -q 1; then
  sudo -u postgres createdb "${DB_NAME}"
fi

echo "==> Writing .env (local development connection strings)"
if [ ! -f .env ]; then
  cat > .env <<'ENV'
# Local Cloud Agent development environment (generated by .cursor/install.sh)
DATABASE_URL="postgresql://postgres:postgres@127.0.0.1:5432/multitenant"
DIRECT_URL="postgresql://postgres:postgres@127.0.0.1:5432/multitenant"

# Placeholders (not used by the current code paths, mirrored from .env.example)
NEXT_PUBLIC_API_URL="http://localhost:3000/api"
NEXT_PUBLIC_SUPABASE_URL=""
NEXT_PUBLIC_SUPABASE_ANON_KEY=""
ENV
fi

echo "==> Installing Node dependencies"
if [ -f package-lock.json ]; then
  npm ci
else
  npm install
fi

echo "==> Generating Prisma client"
npx prisma generate

echo "==> Applying database migrations"
npx prisma migrate deploy

echo "==> Seeding database (only when empty)"
TENANT_COUNT="$(PGPASSWORD=${DB_PASS} psql -h 127.0.0.1 -U ${DB_USER} -d ${DB_NAME} -tAc 'SELECT count(*) FROM "Tenant";' 2>/dev/null || echo 0)"
if [ "${TENANT_COUNT:-0}" = "0" ]; then
  npx prisma db seed
else
  echo "    Tenant table already has ${TENANT_COUNT} rows; skipping seed."
fi

echo "==> Install complete."
